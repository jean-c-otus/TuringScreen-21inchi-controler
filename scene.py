"""Pillow layer compositor and local persistent font library.

Every frame is rendered from the unmodified background + new sensor values.
The display transport compares *the final pixels*, never a stale PNG preview.
"""
from __future__ import annotations

import functools
import hashlib
import io
import json
import os
import re
import subprocess
import threading
import time
from datetime import datetime
from pathlib import Path

from workspace import FONTS, migrate_legacy_fonts
from runtime_paths import system_environment
import psutil
from PIL import Image, ImageDraw, ImageFilter, ImageFont

SCREEN_SIZE = 480
PROJECT = Path(__file__).resolve().parent
FONT_DIR = FONTS
FONT_DIR.mkdir(parents=True, exist_ok=True)
migrate_legacy_fonts()
INDEX = FONT_DIR / "index.json"
FONT_LOCK = threading.RLock()
FONT_EXTS = {".ttf", ".otf", ".ttc"}
MAX_FONT_BYTES = 8 * 1024 * 1024
MAX_FONTS = 50

SENSOR_NAMES = {
    "cpu_temp": "CPU 温度", "cpu_load": "CPU 使用率",
    "gpu_temp": "GPU 温度", "gpu_load": "GPU 使用率",
    "gpu_memory": "显存使用率", "ram": "内存使用率",
    "clock": "时间",
}

_sensor_cache = {"ts": 0.0, "value": {}}


def hwmon_cpu_temp():
    for base in Path("/sys/class/hwmon").glob("hwmon*"):
        try:
            if (base / "name").read_text().strip() == "coretemp":
                return round(int((base / "temp1_input").read_text()) / 1000, 1)
        except (OSError, ValueError):
            continue
    return None


def sensor_snapshot(force=False):
    if not force and time.monotonic() - _sensor_cache["ts"] < 0.6:
        return dict(_sensor_cache["value"])
    ram = psutil.virtual_memory()
    cpu_temp = hwmon_cpu_temp()
    if cpu_temp is None:
        try:
            for name in ("coretemp", "k10temp", "cpu_thermal"):
                readings = psutil.sensors_temperatures().get(name)
                if readings:
                    cpu_temp = readings[0].current
                    break
        except (AttributeError, OSError):
            pass
    result = {
        "cpu_temp": None if cpu_temp is None else round(cpu_temp, 1),
        "cpu_load": round(psutil.cpu_percent(interval=None), 1),
        "gpu_temp": None, "gpu_load": None, "gpu_memory": None,
        "ram": round(ram.percent, 1),
        # This provides an unmistakably changing observable diagnostic layer.
        "clock": datetime.now().strftime("%H:%M:%S"),
    }
    try:
        proc = subprocess.run([
            "nvidia-smi",
            "--query-gpu=temperature.gpu,utilization.gpu,memory.used,memory.total",
            "--format=csv,noheader,nounits",
        ], capture_output=True, text=True, timeout=2, env=system_environment())
        if proc.returncode == 0 and proc.stdout.strip():
            temp, utilization, used, total = map(
                float, proc.stdout.strip().splitlines()[0].split(",")
            )
            result.update(
                gpu_temp=round(temp, 1),
                gpu_load=round(utilization, 1),
                gpu_memory=round(100 * used / total, 1) if total else None,
            )
    except (OSError, ValueError, subprocess.TimeoutExpired):
        pass
    _sensor_cache.update(ts=time.monotonic(), value=result)
    return dict(result)


def _read_index():
    if not INDEX.is_file():
        return {}
    try:
        value = json.loads(INDEX.read_text(encoding="utf-8"))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def font_list():
    """Only return trusted filenames generated by our own hash-based uploader."""
    with FONT_LOCK:
        index = _read_index()
        return [
            {"id": key, "name": entry["name"], "ext": entry["ext"]}
            for key, entry in sorted(index.items(), key=lambda kv: kv[1]["name"].casefold())
            if re.fullmatch("[a-f0-9]{32}", key) and
               entry.get("ext") in FONT_EXTS and
               (FONT_DIR / (key + entry["ext"])).is_file()
        ]


def font_file(font_id):
    if not isinstance(font_id, str) or not re.fullmatch("[a-f0-9]{32}", font_id):
        raise ValueError("字体标识无效")
    with FONT_LOCK:
        index = _read_index()
        row = index.get(font_id)
        if not row or row.get("ext") not in FONT_EXTS:
            raise ValueError("字体不存在")
        path = FONT_DIR / (font_id + row["ext"])
        if not path.is_file():
            raise ValueError("字体文件不存在")
        return path


def install_font(name, content):
    """Persist only a valid small TTF / OTF / TTC binary, not arbitrary paths."""
    suffix = Path(name or "").suffix.lower()
    if suffix not in FONT_EXTS:
        raise ValueError("仅支持 TTF、OTF、TTC 字体")
    if not content or len(content) > MAX_FONT_BYTES:
        raise ValueError("字体文件必须小于 8 MB")
    try:
        font = ImageFont.truetype(io.BytesIO(content), size=32)
        font.getbbox("文字 ABC 123")
    except (OSError, ValueError, TypeError) as exc:
        raise ValueError("无法解析字体文件，请使用标准 TTF/OTF/TTC") from exc

    font_id = hashlib.sha256(content).hexdigest()[:32]
    safe_name = re.sub(r"[\x00-\x1f/\\<>]", "", Path(name).name).strip()[:90] or "Uploaded font"
    with FONT_LOCK:
        index = _read_index()
        if font_id not in index and len(index) >= MAX_FONTS:
            raise ValueError("最多保存 50 款字体")
        ext = index.get(font_id, {}).get("ext", suffix)
        target = FONT_DIR / (font_id + ext)
        if not target.exists():
            tmp = target.with_suffix(target.suffix + ".tmp")
            tmp.write_bytes(content)
            os.replace(tmp, target)
        index[font_id] = {"name": safe_name, "ext": ext}
        tmp_manifest = INDEX.with_suffix(".tmp")
        tmp_manifest.write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")
        os.replace(tmp_manifest, INDEX)
    return {"id": font_id, "name": safe_name, "ext": ext}


def _valid_color(value, label):
    if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise ValueError(f"{label} 颜色必须是 #RRGGBB")
    return value


def normalize_layers(data):
    if isinstance(data, str):
        try:
            data = json.loads(data)
        except json.JSONDecodeError as exc:
            raise ValueError("图层 JSON 不合法") from exc
    if data is None:
        return []
    if not isinstance(data, list) or len(data) > 12:
        raise ValueError("最多支持 12 个图层")

    output = []
    for obj in data:
        if not isinstance(obj, dict):
            raise ValueError("图层格式错误")
        kind = str(obj.get("type", "text"))
        if kind not in ("text", "symbol", "sensor"):
            raise ValueError("未知图层类型")
        metric = str(obj.get("metric", "cpu_temp"))
        if metric not in SENSOR_NAMES:
            raise ValueError("无效的传感器指标")
        font_id = str(obj.get("font", "default"))
        if font_id != "default":
            font_file(font_id)
        try:
            precision=int(obj.get("precision",1))
            x = int(float(obj.get("x", 150)))
            y = int(float(obj.get("y", 200)))
            size = int(float(obj.get("size", 30)))
            weight = int(obj.get("weight", 400))
            letter_space = float(obj.get("tracking", 0))
            outline = int(obj.get("outline", 0))
            opacity = int(obj.get("opacity", 100))
            shadow = bool(obj.get("shadow", False))
            background = bool(obj.get("background", False))
        except (TypeError, ValueError) as exc:
            raise ValueError("图层数字设置无效") from exc

        alignment = str(obj.get("align", "left"))
        if alignment not in ("left", "center", "right"):
            raise ValueError("文本对齐方式无效")
        if not (
            0 <= x <= 479 and 0 <= y <= 479 and 12 <= size <= 100
            and weight in (400, 700)
            and 0<=precision<=2
            and -2 <= letter_space <= 20
            and 0 <= outline <= 5 and 20 <= opacity <= 100
        ):
            raise ValueError("图层坐标或样式设置超出范围")

        prefix=obj.get("prefix",None)
        suffix=obj.get("suffix",None)
        if prefix is None:
            prefix = "" if metric=="clock" else SENSOR_NAMES[metric] + " "
        if suffix is None:
            suffix = "" if metric=="clock" else ("°C" if metric.endswith("_temp") else "%")
        output.append({
            "type": kind,
            "text": str(obj.get("text", ""))[:80],
            "metric": metric,
            "prefix":str(prefix)[:60],
            "suffix":str(suffix)[:30],
            "precision":precision,
            "x": x, "y": y,
            "size": size,
            "color": _valid_color(obj.get("color", "#ffffff"), "文字"),
            "font": font_id,
            "weight": weight,
            "italic": bool(obj.get("italic", False)),
            "tracking": letter_space,
            "align": alignment,
            "outline": outline,
            "outline_color": _valid_color(obj.get("outline_color", "#15202b"), "描边"),
            "shadow": shadow,
            "background": background,
            "background_color": _valid_color(obj.get("background_color", "#15202b"), "文字底色"),
            "opacity": opacity,
        })
    return output


@functools.lru_cache(maxsize=128)
def get_font(size, kind="text", font_id="default"):
    if font_id != "default":
        return ImageFont.truetype(str(font_file(font_id)), size)
    names = (
        ("Noto Sans Symbols 2", "Noto Sans CJK SC", "DejaVu Sans")
        if kind == "symbol" else
        ("Noto Sans CJK SC", "DejaVu Sans", "Noto Sans Symbols 2")
    )
    for family in names:
        try:
            result = subprocess.run(
                ["fc-match", "-f", "%{file}", family],
                capture_output=True, text=True, timeout=2,
            )
            if result.returncode == 0 and Path(result.stdout.strip()).is_file():
                return ImageFont.truetype(result.stdout.strip(), size)
        except (OSError, ValueError, subprocess.TimeoutExpired):
            pass
    return ImageFont.load_default(size=size)


def text_of(layer, values):
    """Never cache the resulting label: the middle value is always freshly read.
    Users can edit every non-numeric part of the sensor's displayed label.
    """
    if layer["type"] != "sensor":
        return layer["text"]
    metric=layer["metric"]
    prefix=layer.get("prefix", "" if metric=="clock" else SENSOR_NAMES[metric]+" ")
    suffix=layer.get("suffix", "" if metric=="clock" else ("°C" if metric.endswith("_temp") else "%"))
    value=values.get(metric)
    if metric=="clock":
        mid=str(value) if value is not None else "--:--:--"
    elif value is None:
        mid="--"
    else:
        n=int(layer.get("precision",1))
        mid=f"{float(value):.{n}f}"
    return f"{prefix}{mid}{suffix}"


def _glyph_width(font, text, tracking):
    if tracking == 0:
        return font.getlength(text)
    return sum(font.getlength(ch) for ch in text) + max(0, len(text) - 1) * tracking


def _draw_text(draw, xy, message, font, fill, stroke_w, stroke_fill, tracking):
    if not tracking:
        draw.text(xy, message, font=font, fill=fill, stroke_width=stroke_w, stroke_fill=stroke_fill)
        return
    x, y = xy
    for char in message:
        draw.text((round(x), y), char, font=font, fill=fill,
                  stroke_width=stroke_w, stroke_fill=stroke_fill)
        x += font.getlength(char) + tracking


def _draw_layer(canvas, layer, content):
    if not content:
        return
    font = get_font(layer["size"], layer["type"], layer["font"])
    tracking = layer["tracking"]
    # Separate transparent glyph image, so shadow, synthetic italic and alpha
    # are identical in full and partial sends (including sensor values).
    bbox = font.getbbox(content)
    w = max(1, int(_glyph_width(font, content, tracking) + 16))
    h = max(1, bbox[3] - bbox[1] + 16)
    glyph = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    g = ImageDraw.Draw(glyph)
    origin = (8, 8 - bbox[1])
    weight = 1 if layer["weight"] == 700 else 0
    outline = layer["outline"]
    if outline:
        _draw_text(g, origin, content, font, layer["color"],
                   outline + weight, layer["outline_color"], tracking)
    _draw_text(g, origin, content, font, layer["color"],
               weight, layer["color"], tracking)
    if layer["italic"]:
        shear = .23
        extra = round(h * shear)
        glyph = glyph.transform(
            (w + extra, h), Image.Transform.AFFINE,
            (1, -shear, shear * h, 0, 1, 0),
            resample=Image.Resampling.BICUBIC,
        )
        w += extra

    align = layer["align"]
    x = layer["x"] - (w if align == "right" else w // 2 if align == "center" else 0)
    y = layer["y"]
    padded = Image.new("RGBA", (w + 22, h + 22), (0, 0, 0, 0))
    if layer["background"]:
        bg = ImageDraw.Draw(padded)
        color = tuple(bytes.fromhex(layer["background_color"][1:]))
        bg.rounded_rectangle((0, 0, w + 21, h + 21), radius=7,
                             fill=(*color, 165))
    if layer["shadow"]:
        a = glyph.getchannel("A")
        blurred = a.filter(ImageFilter.GaussianBlur(2))
        shadow = Image.new("RGBA", glyph.size, (0, 0, 0, 0))
        shadow.putalpha(blurred.point(lambda value: int(value * 0.55)))
        padded.alpha_composite(shadow, (14, 15))
    padded.alpha_composite(glyph, (9, 9))
    if layer["opacity"] != 100:
        alpha = padded.getchannel("A")
        padded.putalpha(alpha.point(lambda value: round(value * layer["opacity"] / 100)))

    canvas.alpha_composite(padded, (round(x) - 9, round(y) - 9))


def compose(frame, layers, sensors=None):
    """The ONLY authoritative frame builder (preview, benchmark and live)."""
    image = frame.convert("RGBA")
    layers = normalize_layers(layers)
    if not layers:
        return image.convert("RGB")
    values = sensor_snapshot() if sensors is None else sensors
    for layer in layers:
        _draw_layer(image, layer, text_of(layer, values))
    return image.convert("RGB")


def compose_overlay(layers, sensors=None):
    """Only the additional layers, with transparent pixels outside them."""
    image = Image.new("RGBA", (480, 480), (0, 0, 0, 0))
    values = sensor_snapshot() if sensors is None else sensors
    for layer in normalize_layers(layers):
        _draw_layer(image, layer, text_of(layer, values))
    return image


def render_preview(base, preview, kind, layers, fps):
    """Static preview is a snapshot; live sensor values are refreshed per frame."""
    import tempfile
    from media import iter_video_frames, run_ffmpeg
    from threading import Event

    layers = normalize_layers(layers)
    values = sensor_snapshot(force=True)
    if kind == "image":
        with Image.open(base) as original:
            compose(original, layers, values).save(preview, "PNG", optimize=True)
        return

    with tempfile.TemporaryDirectory(prefix="turing-preview-") as folder:
        temp = Path(folder)
        count = 0
        stream = iter_video_frames(base, Event())
        try:
            for frame in stream:
                count += 1
                compose(frame, layers, values).save(temp / f"frame_{count:04d}.png")
        finally:
            stream.close()
        if not count:
            raise RuntimeError("视频无法生成任何预览帧")
        run_ffmpeg([
            "-framerate", str(fps), "-i", str(temp / "frame_%04d.png"),
            "-an", "-sn", "-c:v", "libx264", "-preset", "fast",
            "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
            str(preview),
        ], timeout=180)
